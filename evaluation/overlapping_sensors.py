"""
Phase 7A — deterministic overlapping-sensor fault experiments.

Run with:      python -m evaluation.overlapping_sensors

Compares three ways of turning {primary, surface, backup} temperature
readings into the single `temp_c` channel the Bayesian filter consumes:

  naive_single   - primary sensor only (what a classical single-thermistor
                   BMS effectively does).
  naive_average  - unweighted mean of all three readings.
  reliability_fusion - models.sensor_fusion.fuse_overlapping_sensors.

The underlying TRUE temperature and hidden-state labels come from the
existing, UNCHANGED Cooling-System-Failure synthetic scenario (a run that
genuinely becomes dangerous, so false alarms/misses are meaningful) - no
scenario label, threshold or ground-truth definition is touched. The
`primary` sensor's reading is then perturbed with an explicit, controlled
fault (bias/stuck/noise), using a fault-injection RNG stream that is
entirely separate from the simulator's own, so the simulator's frozen
baseline (temp_true, true_state, temp_primary/surface/backup as generated by
data/battery_simulator.py) is read but never mutated in place.

The inference engine is never told which fault (if any) was injected - it
only ever sees the three raw readings, exactly like models/fault_diagnosis.py
never sees the simulator's `sensor_faulty_true` column.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Callable, Dict, List

import numpy as np
import pandas as pd

from config import model_parameters as P
from data.battery_simulator import simulate_pack
from models.bayesian_filter import BayesianFilter
from models.risk_forecast import dangerous_probability
from models.sensor_fusion import fuse_overlapping_sensors

PROJECT_ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = PROJECT_ROOT / "results" / "overlapping_sensors"

FAULT_SEED = 7  # independent of the simulator's own seed
FAULT_SENSOR = "primary"
POSITIVE_BIAS_C = 25.0
NEGATIVE_BIAS_C = -25.0
NOISE_EXTRA_STD_C = 6.0
STUCK_FROM_STEP = 30


def _base_frame(cell: int = 2, seed: int = 20240, n_steps: int = 180) -> pd.DataFrame:
    sim = simulate_pack(scenario="Cooling-System Failure", affected_cell=cell, seed=seed, n_steps=n_steps)
    return sim.frame[sim.frame["cell"] == cell].sort_values("step").reset_index(drop=True)


FaultFn = Callable[[np.ndarray, np.random.Generator], np.ndarray]


def _no_fault(vals: np.ndarray, rng: np.random.Generator) -> np.ndarray:
    return vals.copy()


def _positive_bias(vals: np.ndarray, rng: np.random.Generator) -> np.ndarray:
    return vals + POSITIVE_BIAS_C


def _negative_bias(vals: np.ndarray, rng: np.random.Generator) -> np.ndarray:
    return vals + NEGATIVE_BIAS_C


def _stuck(vals: np.ndarray, rng: np.random.Generator) -> np.ndarray:
    out = vals.copy()
    out[STUCK_FROM_STEP:] = vals[STUCK_FROM_STEP]
    return out


def _noisy(vals: np.ndarray, rng: np.random.Generator) -> np.ndarray:
    return vals + rng.normal(0.0, NOISE_EXTRA_STD_C, size=vals.shape)


FAULT_CONDITIONS: Dict[str, FaultFn] = {
    "all_healthy": _no_fault,
    "positive_bias": _positive_bias,
    "negative_bias": _negative_bias,
    "stuck_sensor": _stuck,
    "noisy_sensor": _noisy,
}


def _temp_rate(temp_c: np.ndarray, dt_min: float) -> np.ndarray:
    rate = np.zeros_like(temp_c)
    rate[1:] = (temp_c[1:] - temp_c[:-1]) / dt_min
    return rate


def _run_filter(temp_c: np.ndarray, dt_min: float) -> np.ndarray:
    """P(dangerous) trajectory from a temp_c-only observation stream (no
    voltage/gas/neighbour channel - isolating exactly the effect of the
    fusion method under test)."""
    rate = _temp_rate(temp_c, dt_min)
    f = BayesianFilter()
    out = np.empty_like(temp_c)
    for i in range(len(temp_c)):
        step = f.update({"temp_c": float(temp_c[i]), "temp_rate": float(rate[i])})
        out[i] = dangerous_probability(step.posterior)
    return out


def run_condition(frame: pd.DataFrame, fault_name: str) -> Dict[str, object]:
    fault_fn = FAULT_CONDITIONS[fault_name]
    rng = np.random.default_rng(FAULT_SEED)

    readings = {
        "primary": frame["temp_primary"].to_numpy(dtype=float),
        "surface": frame["temp_surface"].to_numpy(dtype=float),
        "backup": frame["temp_backup"].to_numpy(dtype=float),
    }
    readings[FAULT_SENSOR] = fault_fn(readings[FAULT_SENSOR], rng)

    n = len(frame)
    dt_min = P.DT_MINUTES
    temp_true = frame["temp_true"].to_numpy(dtype=float)
    true_dangerous = frame["true_state"].isin(P.DANGEROUS_STATES).to_numpy()

    naive_single = readings["primary"].copy()
    naive_average = np.mean([readings[s] for s in P.OVERLAPPING_SENSOR_NAMES], axis=0)

    fused = np.empty(n)
    reliability_trace: Dict[str, List[float]] = {s: [] for s in P.OVERLAPPING_SENSOR_NAMES}
    disagreement = np.empty(n)
    for i in range(n):
        r = fuse_overlapping_sensors({s: readings[s][i] for s in P.OVERLAPPING_SENSOR_NAMES})
        fused[i] = r.fused_temp_c
        disagreement[i] = r.disagreement_c
        for s in P.OVERLAPPING_SENSOR_NAMES:
            reliability_trace[s].append(r.reliability[s])

    methods = {"naive_single": naive_single, "naive_average": naive_average, "reliability_fusion": fused}
    result: Dict[str, object] = {"fault": fault_name, "methods": {}}
    for name, temp_c in methods.items():
        p_dangerous = _run_filter(temp_c, dt_min)
        alarm = p_dangerous > 0.5
        tp = int(np.sum(alarm & true_dangerous))
        fp = int(np.sum(alarm & ~true_dangerous))
        fn = int(np.sum(~alarm & true_dangerous))
        result["methods"][name] = {
            "mean_abs_temp_error_c": float(np.mean(np.abs(temp_c - temp_true))),
            "false_alarms": fp,
            "missed_dangerous": fn,
            "true_positives": tp,
            "max_p_dangerous": float(p_dangerous.max()),
        }
    result["mean_disagreement_c"] = float(np.mean(disagreement))
    result["mean_reliability"] = {s: float(np.mean(v)) for s, v in reliability_trace.items()}
    return result


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    frame = _base_frame()
    results = [run_condition(frame, name) for name in FAULT_CONDITIONS]

    (OUT_DIR / "summary.json").write_text(json.dumps(results, indent=2), encoding="utf-8")

    rows = []
    for r in results:
        for method, m in r["methods"].items():
            rows.append({"fault": r["fault"], "method": method, **m})
    table = pd.DataFrame(rows)
    table.to_csv(OUT_DIR / "comparison.csv", index=False)

    print(table.to_string(index=False))
    print(f"\nWritten to {OUT_DIR}")
    return 0


if __name__ == "__main__":
    import sys

    sys.exit(main())
